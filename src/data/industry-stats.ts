/**
 * Find a stat by domain slug with fuzzy matching.
 * Strips non-alpha characters and checks for substring inclusion,
 * so "real-estate" matches "real estate", "e-commerce" matches "ecommerce", etc.
 */
export function getIndustryStat(domain: string): IndustryStat | undefined {
  const normalized = domain.toLowerCase().replace(/[^a-z]/g, "");
  return industryStats.find((s) => {
    const statDomain = s.domain.toLowerCase().replace(/[^a-z]/g, "");
    return (
      statDomain === normalized ||
      normalized.includes(statDomain) ||
      statDomain.includes(normalized)
    );
  });
}

/**
 * Map tool categories (e.g. "AI Coding", "AI Legal") to an industry domain stat.
 * Falls back to fuzzy-matching the category string directly.
 */
export function getStatForCategory(
  category: string,
): IndustryStat | undefined {
  const categoryMap: Record<string, string> = {
    "AI Coding": "saas",
    "AI Writing": "marketing",
    "AI Design": "media",
    "AI Data": "finance",
    "AI Automation": "saas",
    "AI Customer Service": "retail",
    "AI Marketing": "marketing",
    "AI Sales": "consulting",
    "AI HR": "hr",
    "AI Legal": "legal",
    "AI Healthcare": "healthcare",
    "AI Education": "education",
    "AI Finance": "finance",
    "AI Security": "government",
  };
  const mapped = categoryMap[category] || category.toLowerCase();
  return getIndustryStat(mapped);
}
